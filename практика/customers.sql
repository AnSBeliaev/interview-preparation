-- Черновик таблицы customers. Напишите команду здесь, затем вставьте её в psql.
-- В postgres=# напишите CREATE TABLE customers ( и дальше по одной колонке на строку.
-- 
-- Номер клиента выдаёт сама база. По этому номеру находится ровно один клиент.
-- Почта обязательна. Двух одинаковых быть не может. Длиннее 320 символов она не бывает.
-- Имя обязательно. Заранее его длину не ограничивают.
-- Телефон можно не указывать. Если он есть, он не длиннее 64 символов.
-- Код страны — ровно две буквы. Если его не передали, записывается RU.
-- День рождения можно не указывать.
-- Клиент либо активен, либо нет. Пустым это поле не бывает. Если при добавлении ничего не передали, записывается «да».
-- Момент создания обязателен. Если его не передали, база ставит текущее время.
-- Последнюю колонку пишите без запятой и закройте команду символами );. Когда база ответит CREATE TABLE, пришлите текст сюда.
CREATE TABLE customers (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    email varchar(320) NOT NULL UNIQUE,
    name text NOT NULL,
    phone varchar(64),
    country_code char(2) DEFAULT 'RU',
    CONSTRAINT chk_country_code_format CHECK (country_code ~ '^[A-Z]{2}$'),
    birth_date date,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamp NOT NULL DEFAULT now()
);