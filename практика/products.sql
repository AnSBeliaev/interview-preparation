-- Черновик таблицы products. Напишите команду здесь, затем вставьте её в psql.
-- В postgres=# вставьте CREATE TABLE products ( и дальше по одной колонке на строку.
--
-- Номер товара выдаёт сама база. Это обычное целое, не самое большое. По номеру находится ровно один товар.
-- Артикул обязателен, не длиннее 64 символов, двух одинаковых быть не может.
-- Название обязательно, длину заранее не ограничивают.
-- Цена обязательна, с копейками, меньше нуля быть не может.
-- Вес в килограммах можно не указывать. Точность до грамма здесь не нужна.
-- Рейтинг можно не указать. Если он есть, это дробное число от 0 до 5.
-- Остаток на складе — маленькое целое. Если его не передали, записывается 0. Ограничение «не меньше нуля» пока не пишите, его добавите отдельной командой.
-- Дополнительные свойства хранятся как JSON, внутри которого потом будут искать. Пустым это поле не бывает. Если свойства не передали, записывается пустой объект {}.
-- Рядом лежит второй JSON: старый текст ровно в том виде, в каком его прислали. Его можно не заполнять.
-- Внешний номер — длинный случайный uuid. Если его не передали, база собирает его сама. Пустым он не бывает.
-- Последнюю колонку пишите без запятой и закройте команду символами );. Когда база ответит CREATE TABLE, пришлите текст сюда.
CREATE TABLE products (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    sku varchar(64) NOT NULL UNIQUE,
    title text NOT NULL,
    price numeric(12, 2) NOT NULL CHECK (price >= 0),
    weight_kg real,
    rating double precision CHECK (rating IS NULL OR (rating >= 0 AND rating <= 5)),
    stock smallint NOT NULL DEFAULT 0,
    attrs jsonb NOT NULL DEFAULT '{}'::jsonb,
    legacy_payload json,
    external_id uuid NOT NULL DEFAULT gen_random_uuid()
);
